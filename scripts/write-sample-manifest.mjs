import { readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const sounds = path.resolve(here, '../assets/sounds')
const files = readdirSync(sounds)
  .filter((name) => name.endsWith('.wav'))
  .sort()

const piano = files.filter((name) => name.startsWith('piano-')).length
const trombone = files.filter((name) => name.startsWith('trombone-')).length
if (piano !== 88 || trombone !== 88) {
  throw new Error(`Expected 88 piano and 88 trombone files, found ${piano} and ${trombone}`)
}

const lines = files.map((name) => {
  const key = name.slice(0, -4)
  return `  ${JSON.stringify(key)}: require(${JSON.stringify(`../assets/sounds/${name}`)}),`
})

const out = `/* Generated by scripts/write-sample-manifest.mjs. */
export const sampleModules: Record<string, number> = {
${lines.join('\n')}
}
`

writeFileSync(path.resolve(here, '../src/sampleManifest.ts'), out)
console.log(`Wrote ${files.length} samples`)
